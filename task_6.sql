-- 1. Открываем транзакцию, чтобы объединить процесс блокировки и обновления в неделимую операцию
BEGIN;
-- 2. Создаем CTE для изоляции, расчета цен и блокировки строк
WITH target_restaurants AS (
  SELECT 
    r.restaurant_uuid,
    -- Извлекаем текущую цену, увеличиваем на 20% и округляем до целого числа
    ROUND((menu -> 'Кофе' ->> 'Капучино')::numeric * 1.20) AS new_price
  FROM cafe.restaurants r
  WHERE menu -> 'Кофе' -> 'Капучино' IS NOT NULL
  FOR UPDATE
)
-- 3. Выполняем обновление основной таблицы, используя данные из CTE
UPDATE cafe.restaurants r
SET menu = jsonb_set(
  r.menu,
  '{Кофе,Капучино}', 
  to_jsonb(tr.new_price)
)
FROM target_restaurants tr
WHERE r.restaurant_uuid = tr.restaurant_uuid;
-- 4. Фиксируем изменения и снимаем блокировку со строк
COMMIT;

/* 
ПОЯСНЕНИЕ ВЫБОРА БЛОКИРОВКИ:
Конструкция FOR UPDATE блокирует выбранные строки на уровне RECORD (строки таблицы).
Она запрещает любым другим транзакциям изменять (UPDATE/DELETE) или повторно блокировать
эти строки до тех пор, пока наша транзакция не завершится (COMMIT/ROLLBACK).
При этом заведения, у которых нет Капучино в меню, не попадают в выборку и остаются
полностью доступными для чтения и записи другими пользователями.
*/


